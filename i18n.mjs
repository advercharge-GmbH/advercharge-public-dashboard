let language = 'en';
export const getLanguage = () => language;
export const locale = () => language === 'de' ? 'de-DE' : 'en-GB';
export function setLanguage(value) { language = value === 'de' ? 'de' : 'en'; }
export function t(message, values = {}) {
  const translated = language === 'de' ? german[message] ?? message : message;
  return translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}

export function applyTranslations(root) {
  root.documentElement.lang = language;
  root.title = t('advercharge | Reach the right driver');
  root.querySelectorAll('[data-i18n]').forEach(element => {
    element.dataset.i18n ||= element.textContent.trim();
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.dataset.i18nAria ||= element.getAttribute('aria-label');
    element.setAttribute('aria-label', t(element.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-content]').forEach(element => {
    element.dataset.i18nContent ||= element.getAttribute('content');
    element.setAttribute('content', t(element.dataset.i18nContent));
  });
  root.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
}

export function setupLanguage(root, onChange, storage) {
  try { setLanguage(storage?.getItem('advercharge-language')); } catch { setLanguage('en'); }
  applyTranslations(root);
  root.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => {
      setLanguage(button.dataset.language);
      try { storage?.setItem('advercharge-language', language); } catch { /* Private browsing may deny storage. */ }
      applyTranslations(root);
      onChange();
    });
  });
}
